// netwarden - one formatting layer (round 10e): numbers, percents, byte sizes, milliseconds
// and the list separator, as the browser's Intl APIs write them in each of the 12 languages.
// The values come from app.js's own `fmt` block (cut out of the file and evaluated), so the
// fixture pins the page; tests/test_round10e.py checks the server's i18n.num / pct / size /
// ms / list_sep against the same file (that runs without node). Run from the repo root:
//     node tests/js/intl_formats_test.js            compare with tests/fixtures/intl_formats.json
//     node tests/js/intl_formats_test.js --write    regenerate it (after a deliberate change)
// It exits non-zero when app.js and the fixture disagree.
'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const fixture = path.join(root, 'tests', 'fixtures', 'intl_formats.json');
const src = fs.readFileSync(path.join(root, 'netwarden', 'static', 'app.js'), 'utf8');
const start = src.indexOf('let F = null;'), end = src.indexOf('\n};\n', src.indexOf('const fmt = {'));
assert.ok(start > 0 && end > start, 'the fmt block was not found in app.js');
const langs = fs.readdirSync(path.join(root, 'netwarden', 'locales')).filter(f => f.endsWith('.json'))
  .map(f => f.slice(0, -5)).sort();

// representative values: grouping thresholds, half-way rounding, unit steps
const NUMS = [[0, 0], [7, 0], [1234, 0], [12345, 0], [1234567, 0], [-2, 0], [3.25, 1], [2.25, 1], [0.04, 1],
              [1234.5, 1], [12.0, 1]];
const PCTS = [[0, 0, false], [14, 0, false], [23, 0, false], [118, 0, true], [-37, 0, true], [0.4, 1, false],
              [2.5, 1, false], [100, 0, false]];
const SIZES = [0, 1, 999, 1000, 1500, 121300000, 5300000000, 12500000000, 14512345678, 999960, 3.2e12];
const MS = [0.84, 3.25, 12, 128.4, 1234];
const DAYS = ['2026-10-20', '2026-01-05'];   // i18n.month_day (bedtime nights) = fmt.day

function build(lang) {
  const S = { lang, meta: {} }, T = k => k;
  // eslint-disable-next-line no-new-func
  const M = new Function('S', 'T', 'parseTs', 'nowMs', src.slice(start, end) + '\n};\nfmtInit(); return { fmt, F };')(S, T, () => 0, () => 0);
  const { fmt, F } = M;
  const nf = (d, trim) => new Intl.NumberFormat(F.l, { minimumFractionDigits: trim ? 0 : d, maximumFractionDigits: d });
  const four = new Intl.ListFormat(lang, { type: 'conjunction' }).format(['a', 'b', 'c', 'd']);
  return {
    num: NUMS.flatMap(([v, d]) => [[v, d, false, nf(d, false).format(v)], [v, d, true, nf(d, true).format(v)]]),
    pct: PCTS.map(([v, d, sign]) => [v, d, sign, d ? new Intl.NumberFormat(F.l, { style: 'percent', maximumFractionDigits: d }).format(v / 100)
                                                 : fmt.pct(v / 100, sign)]),
    size: SIZES.map(n => [n, fmt.bytes(n)]),
    ms: MS.map(v => [v, fmt.ms(v)]),
    day: DAYS.map(d => [d, fmt.day(d)]),
    list_sep: four.slice(four.indexOf('a') + 1, four.indexOf('b')),
  };
}

// The CLDR version is recorded: a node with other locale data (CI's preinstalled node, a new
// LTS) may write some values differently - that is not an app.js change, so it is reported and
// skipped, not failed; the server side stays pinned to the fixture (tests/test_round10e.py).
const out = { _note: 'Generated by node tests/js/intl_formats_test.js --write from Intl (CLDR); do not edit by hand.',
              cldr: process.versions.cldr || '', langs: {} };
for (const l of langs) out.langs[l] = build(l);
// one row per line: small diffs when CLDR moves
const text = JSON.stringify(out, null, 1).replace(/\[\s+([^\[\]{}]*?)\s+\]/g, (m, body) => '[' + body.split(/,\s+/).join(', ') + ']') + '\n';
if (process.argv.includes('--write')) {
  fs.writeFileSync(fixture, text);
  console.log('wrote ' + path.relative(root, fixture) + ' (' + langs.length + ' languages)');
  process.exit(0);
}
const want = JSON.parse(fs.readFileSync(fixture, 'utf8'));
if (want.cldr && out.cldr !== want.cldr) {
  console.log('skip: the fixture was made with CLDR ' + want.cldr + ', this node has CLDR ' + (out.cldr || '?')
              + ' (regenerate with --write when moving to it)');
  process.exit(0);
}
let bad = 0;
for (const l of langs) {
  for (const k of Object.keys(out.langs[l])) {
    try { assert.deepStrictEqual(out.langs[l][k], (want.langs[l] || {})[k]); } catch (e) {
      bad++; console.log('DIFF ' + l + ' ' + k + '\n  now:     ' + JSON.stringify(out.langs[l][k]) + '\n  fixture: ' + JSON.stringify((want.langs[l] || {})[k]));
    }
  }
}
if (bad) { console.log(bad + ' difference(s): this Intl / app.js no longer matches the fixture (regenerate with --write if intended)'); process.exit(1); }
console.log('ok  ' + langs.length + ' languages match tests/fixtures/intl_formats.json');
